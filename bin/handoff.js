#!/usr/bin/env node

/**
 * Second Brain Session Continuity & Hot Handover Generator
 * 
 * Generates an authoritative, lean session handoff snapshot (02-provenance/session-handoff.md)
 * to maintain cross-session context for AI agents and human System Analysts without context window bloat.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const targetDir = process.cwd();
const handoffPath = path.join(targetDir, '02-provenance', 'session-handoff.md');

// Helper to safely read file
function readFileSafe(relPath) {
  const p = path.join(targetDir, relPath);
  if (!fs.existsSync(p)) return '';
  return fs.readFileSync(p, 'utf8');
}

// Get recent git commits if in git repo
let recentCommits = 'No recent git commits detected.';
let currentBranch = 'main';
try {
  currentBranch = execSync('git rev-parse --abbrev-ref HEAD 2>/dev/null', { cwd: targetDir }).toString().trim() || 'main';
  recentCommits = execSync('git log -n 5 --oneline 2>/dev/null', { cwd: targetDir }).toString().trim() || 'No commits yet.';
} catch (e) {
  // Not a git repo or git not installed
}

// 1. Inspect Active Deliverables
const pumlCount = fs.existsSync(path.join(targetDir, '04-deliverables', 'sequence-diagrams')) 
  ? fs.readdirSync(path.join(targetDir, '04-deliverables', 'sequence-diagrams')).filter(f => f.endsWith('.puml')).length 
  : 0;

const lldCount = fs.existsSync(path.join(targetDir, '04-deliverables', 'lld')) 
  ? fs.readdirSync(path.join(targetDir, '04-deliverables', 'lld')).filter(f => f.endsWith('.md')).length 
  : 0;

const apiCount = fs.existsSync(path.join(targetDir, '04-deliverables', 'api-contracts')) 
  ? fs.readdirSync(path.join(targetDir, '04-deliverables', 'api-contracts')).filter(f => f.endsWith('.md')).length 
  : 0;

// 2. Inspect Contradictions & Blockers
const contradictionsContent = readFileSafe('02-provenance/contradictions.md');
const openContradictions = [];
const contradictionLines = contradictionsContent.split(/\r?\n/);
contradictionLines.forEach(line => {
  if (line.includes('🔴') || /\|\s+\*\*`C-\d+`\*\*\s+\|/i.test(line)) {
    if (!line.includes('RESOLVED') && !line.includes('ADOPTED')) {
      openContradictions.push(line.trim());
    }
  }
});

// 3. Inspect Active Constraint Branches
const branchDir = path.join(targetDir, '03-constraint-branches');
const activeBranches = [];
if (fs.existsSync(branchDir)) {
  fs.readdirSync(branchDir).forEach(f => {
    if (f.endsWith('.md') && !f.toLowerCase().includes('readme')) {
      activeBranches.push(f.replace('.md', ''));
    }
  });
}

// 4. Inspect Delivery Plan Progress
const deliveryPlan = readFileSafe('02-provenance/delivery-plan.md');
const totalTasks = (deliveryPlan.match(/- \[[ xX]\]/g) || []).length;
const completedTasks = (deliveryPlan.match(/- \[[xX]\]/g) || []).length;
const taskProgress = totalTasks > 0 ? `${completedTasks}/${totalTasks} (${((completedTasks / totalTasks) * 100).toFixed(0)}%)` : 'N/A';

// 5. Construct Lean Session Handoff
const now = new Date().toISOString().replace('T', ' ').substring(0, 19);

const content = `# Session Continuity & Hot Handover

> **Active Session Snapshot & Context Handoff**  
> Auto-generated by \`bin/handoff.js\` to guarantee zero memory loss between AI agent sessions.  
> **Last Synchronized**: \`${now} UTC\` | **Active Branch**: \`${currentBranch}\`

---

## 🧵 1. Live Thread & Operational Focus
- **Current Objective**: Enterprise Second Brain Best-Practice Architecture & Benchmark Preparation.
- **Delivery Progress**: \`${taskProgress}\` completed tasks in \`02-provenance/delivery-plan.md\`.
- **Active Deliverables**:
  - \`${pumlCount}\` Core Sequence Diagrams in \`04-deliverables/sequence-diagrams/\`
  - \`${apiCount}\` REST/JSON API Contracts in \`04-deliverables/api-contracts/\`
  - \`${lldCount}\` 3-Pillar Low-Level Designs in \`04-deliverables/lld/\`
- **Active Trade-Off Branches**: ${activeBranches.length > 0 ? activeBranches.map(b => `\`${b}\``).join(', ') : 'None (All adopted)'}

---

## 🛑 2. Critical Blockers & Pending Decisions
${openContradictions.length > 0 
  ? openContradictions.map((c, i) => `${i + 1}. ${c}`).join('\n')
  : '✅ **Zero Active Blockers**: All contradictions arbitrated via accepted ADRs in `05-adrs/`.'}

---

## 🔄 3. Recent Repository Changes
\`\`\`text
${recentCommits}
\`\`\`

---

## 🎯 4. Immediate Next Actions (Boot Priority)
1. **Verify Integrity**: Run \`npm run audit\` to assert 100% provenance tag coverage and zero active hard-blocks.
2. **Benchmark Readiness**: Run \`npm run readiness\` to inspect the 30-dimension Architecture Readiness Index (target: >= 95% Grade A+).
3. **Execute Delivery Tasks**: If new CR/features arrive, use \`/brain-branch\` for exploration, \`/brain-adopt\` for ADR record, and \`/brain-deliver\` for synthesis.
4. **Update Handoff**: At the close of heavy sessions, rerun \`npm run handoff\` to record updated thread state.
`;

fs.writeFileSync(handoffPath, content, 'utf8');
console.log(`\n✅ Session handoff generated successfully: 02-provenance/session-handoff.md\n`);
